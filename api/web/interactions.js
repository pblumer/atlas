// Who a process talks to (ADR-0559 §7, §8), drawn as a BPMN collaboration: one pool
// per participant — who only sends to the process above it, the process in the
// middle, everybody it sends to below — every pool collapsed by default, and one
// message flow per exchange. A white box expands to the diagram it was deployed with,
// and its message flows then dock on the elements that send and receive. A replay
// plays only the messages, along those flows.
//
// The page reads two routes and computes nothing of its own about who sent what:
//   - GET /api/v1/process-interactions answers the graph — participants, each exchange
//     with its possible and observed layer, the sends that reached nobody, the
//     center's ports;
//   - GET /api/v1/process-interactions/replay lists the same arrivals one by one, page
//     by page, read backwards until the history begins, then followed with `after`.
// Both attribute rows the same way on the server, under the event log's rule of who
// reads what, so what the replay plays is what the graph counts. The collaboration is
// generated by interactions-bpmn.js and rendered by the same bpmn-js the Modeler and
// the collaboration replay of ADR-0038 use.
//
// A message flow is always dashed in BPMN, so the layers are told apart by colour and
// caption: observed flows are drawn dark with their count, possible-only ones light,
// and an observed flow the newest definitions no longer allow in the attention colour.

import { t } from "./i18n.js";
import { fmtDateTime } from "./datefmt.js";
import { build, edgeKey } from "./interactions-bpmn.js";

const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) =>
  ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

// The replay.
const LIVE_MS = 3000;         // how often Live asks for what came after the newest event
const MAX_EVENTS = 5000;      // how many events the page holds; the oldest go first
const PAGE = 1000;            // events per page read
const TICK_MS = 700;          // one replay step
const SPEEDS = [1, 5, 25];    // events per step; above one the step is drawn as counts

const WINDOWS = [["24h", "ix.window.day"], ["168h", "ix.window.week"], ["", "ix.window.retention"]];

// label is how a participant is named. A process carries the name it was deployed
// under; a black box is named by its kind, and the one outside the reader's view has
// no name at all, on purpose (ADR-0472 §5).
function label(p) {
  switch (p.kind) {
    case "process": return p.name || p.processId;
    case "inbound-watch": return p.name || p.connectorId;
    case "product-action": return p.name ? `${p.name} · ${p.action}` : `${p.productId} · ${p.action}`;
    case "publish": return t("ix.kind.publish");
    case "inbound": return t("ix.kind.inbound");
    case "directed": return t("ix.kind.directed");
    case "removed": return t("ix.kind.removed");
    case "outside-view": return t("ix.kind.outside");
  }
  return p.id;
}

function kindHint(p) {
  switch (p.kind) {
    case "process": return (p.center ? t("ix.kind.center") : t("ix.kind.process")) + (p.inactive ? " · " + t("ix.kind.inactive") : "");
    case "inbound-watch": return t("ix.kind.watch", { kind: p.workerKind || "" });
    case "product-action": return t("ix.kind.product");
    case "outside-view": return t("ix.kind.outsideHint");
  }
  return t("ix.kind.blackbox");
}

// flowName is a message flow's caption: the name, and what was observed of it.
function flowName(e) {
  if (!e.observed) return t("ix.edge.possible", { message: e.message });
  const started = e.observed.started ? t("ix.edge.started", { n: e.observed.started }) : "";
  return t("ix.edge.observed", { message: e.message, n: e.observed.received }) + started;
}

const flowLayer = (e) => (!e.observed ? "ix-possible" : e.possible ? "ix-observed" : "ix-not-possible");

// fmtRetention says a Go duration such as 720h0m0s in days when it is whole days.
export function fmtRetention(d) {
  const m = /^(\d+)h0m0s$/.exec(d || "");
  if (m && Number(m[1]) % 24 === 0) return t("ix.days", { n: Number(m[1]) / 24 });
  return d || "";
}

export async function viewInteractions({ api, view, processId, isSuperseded }) {
  const params = new URLSearchParams((location.hash.split("?")[1] || ""));
  let windowArg = params.get("window") ?? "24h";
  if (!WINDOWS.some(([w]) => w === windowArg)) windowArg = "24h";

  view.innerHTML = `
    <div class="between">
      <h1 id="ix-title">${esc(t("ix.title", { name: processId }))}</h1>
      <span class="row" style="gap:8px;align-items:center">
        <select id="ix-window" aria-label="${esc(t("ix.window.label"))}" style="width:auto">${WINDOWS.map(([w, k]) =>
          `<option value="${esc(w)}"${w === windowArg ? " selected" : ""}>${esc(t(k))}</option>`).join("")}</select>
        <button class="btn neutral" id="ix-expand-all">${esc(t("ix.expandAll"))}</button>
        <button class="btn neutral" id="ix-collapse-all">${esc(t("ix.collapseAll"))}</button>
      </span>
    </div>
    <p class="muted">${t("ix.intro")}</p>
    <div class="card ix-card">
      <div id="ix-legend" class="ix-legend muted">${t("ix.legend")}</div>
      <div id="ix-canvas" class="ix-canvas"><p class="muted">${esc(t("ix.loading"))}</p></div>
      <div id="ix-notes"></div>
    </div>
    <div class="card ix-card">
      <h2>${esc(t("ix.replay.title"))}</h2>
      <div class="muted" id="ix-history"></div>
      <div class="row ix-transport" style="gap:8px;align-items:center;flex-wrap:wrap;margin:8px 0">
        <button class="btn neutral" id="ix-rewind" title="${esc(t("ix.replay.rewind"))}">⏮</button>
        <button class="btn" id="ix-play">${esc(t("ix.replay.play"))}</button>
        <button class="btn neutral" id="ix-step" title="${esc(t("ix.replay.step"))}">⏭</button>
        <select id="ix-speed" aria-label="${esc(t("ix.replay.speed"))}" style="width:auto">${SPEEDS.map((s) =>
          `<option value="${s}">${esc(t("ix.replay.perStep", { n: s }))}</option>`).join("")}</select>
        <input type="range" id="ix-scrub" min="0" max="0" value="0" aria-label="${esc(t("ix.replay.scrub"))}" style="flex:1;min-width:160px">
        <label><input type="checkbox" id="ix-live"> ${esc(t("ix.replay.live"))}</label>
      </div>
      <div class="muted" id="ix-now"></div>
      <div class="muted" id="ix-mode"></div>
      <ol id="ix-feed" class="ix-feed"></ol>
    </div>`;

  const $ = (id) => view.querySelector("#" + id);
  const expanded = new Set();     // participant ids of expanded white boxes
  const models = new Map();       // participant id → its deployed model's XML
  const portsCache = new Map();   // process id → ports, read from that process's own graph
  let graph = null;
  let surface = null;             // the bpmn-js canvas
  let drawn = null;               // what build answered for the drawing on screen
  let drawing = Promise.resolve();

  const query = (path, extra) => {
    const q = new URLSearchParams({ processId, ...extra });
    if (windowArg) q.set("window", windowArg);
    return `${path}?${q}`;
  };

  // ---------- the collaboration ----------

  const portsOf = (p) => (p.center ? graph.ports : portsCache.get(p.processId));

  const render = async () => {
    if (!surface) {
      const { collaborationCanvas } = await import("./editor.js");
      if (isSuperseded()) return;
      surface = await collaborationCanvas($("ix-canvas"));
    }
    const shown = new Map([...expanded].filter((id) => models.has(id)).map((id) => [id, models.get(id)]));
    drawn = build({ graph, labelOf: label, flowName, expanded: shown, portsOf });
    // The canvas is as tall as the collaboration drawn at the page's width, within
    // bounds, so a fit neither shrinks three pools to a strip nor stretches one.
    const box = $("ix-canvas");
    const scale = Math.min(1, (box.clientWidth || 1000) / drawn.width);
    box.style.height = `${Math.round(Math.min(900, Math.max(260, drawn.height * scale + 60)))}px`;
    await surface.show(drawn.xml);
    if (isSuperseded()) return;
    const viewer = surface.viewer;
    const canvas = viewer.get("canvas"), overlays = viewer.get("overlays");
    canvas.zoom("fit-viewport");
    for (const p of graph.participants) {
      const pool = drawn.pools.get(p.id);
      if (!pool) continue;
      const marks = [p.center ? "ix-center" : "", p.kind === "process" ? "ix-white" : "ix-black",
        p.kind === "outside-view" ? "ix-outside" : "", p.inactive ? "ix-inactive" : ""].filter(Boolean);
      for (const m of marks) canvas.addMarker(pool.id, m);
      // Open is what is drawn: a model that could not be placed in its pool stays a
      // collapsed pool, and its button says so.
      const open = !!pool.prefix;
      const controls = p.kind !== "process" ? "" :
        `<button class="ix-pool-toggle" data-id="${esc(p.id)}" title="${esc(open ? t("ix.box.collapse") : t("ix.box.expand"))}">${open ? "−" : "+"}</button>` +
        (p.center ? "" : `<button class="ix-pool-open" data-id="${esc(p.id)}" title="${esc(t("ix.box.open"))}">↗</button>`);
      overlays.add(pool.id, "ix-pool", {
        position: { top: 4, left: 40 },
        html: `<div class="ix-pool-ctl" data-id="${esc(p.id)}">${controls}<span class="ix-pool-hint">${esc(kindHint(p))}</span></div>`,
      });
    }
    for (const e of graph.exchanges) {
      const id = drawn.flows.get(edgeKey(e.from, e.to, e.message));
      if (!id || !viewer.get("elementRegistry").get(id)) continue; // a flow bpmn-js could not draw
      canvas.addMarker(id, flowLayer(e));
      // bpmn-js draws a flow's caption as a shape of its own, named after the flow.
      try { canvas.addMarker(id + "_label", flowLayer(e) + "-label"); } catch { /* no caption drawn */ }
    }
    // What a test, or a curious reader of the page source, needs to find a pool or a
    // flow again.
    $("ix-canvas").dataset.flows = JSON.stringify(Object.fromEntries([...drawn.flows].map(([k, v]) => [k.split("\u0000").join(" | "), v])));
    $("ix-canvas").dataset.pools = JSON.stringify(Object.fromEntries([...drawn.pools].map(([k, v]) => [k, v.id])));

    const notes = [];
    if (!graph.exchanges.length) notes.push(`<p class="muted">${esc(t("ix.none"))}</p>`);
    if (graph.unreceived.length) {
      notes.push(`<p class="ix-unreceived"><span class="pill warn">${esc(t("ix.unreceived.title"))}</span> ${graph.unreceived.map((u) =>
        esc(t("ix.unreceived.item", { message: u.message, n: u.count, at: fmtDateTime(u.lastAt) }))).join(" · ")}</p>`);
    }
    if (drawn.skipped.length) {
      notes.push(`<p class="muted ix-self">${esc(t("ix.self", { messages: drawn.skipped.map((e) => e.message).join(", ") }))}</p>`);
    }
    $("ix-notes").innerHTML = notes.join("");
    const center = graph.participants.find((p) => p.center);
    $("ix-title").textContent = t("ix.title", { name: label(center) });
    const partial = graph.observed.partial ? " " + t("ix.partial", { at: fmtDateTime(graph.observed.readFrom) }) : "";
    $("ix-legend").innerHTML = t("ix.legend") + esc(partial);
  };
  // draw serialises the renders: an expand clicked while one imports waits for it.
  const draw = () => (drawing = drawing.then(render).catch((err) => {
    if (!isSuperseded()) $("ix-notes").innerHTML = `<p class="muted">${esc(t("ix.failed", { error: (err && err.message) || err }))}</p>`;
  }));

  // loadModel reads what an expanded white box shows: its deployed diagram, and the
  // ports a neighbour's flows dock on, from its own graph with a window that reads no
  // rows.
  const loadModel = async (p) => {
    const tasks = [];
    if (!models.has(p.id) && p.definitionKey) {
      tasks.push(api("GET", `/api/v1/processes/${p.definitionKey}/xml`)
        .then((xml) => models.set(p.id, typeof xml === "string" ? xml : String(xml)))
        .catch(() => {}));
    }
    if (!p.center && !portsCache.has(p.processId)) {
      tasks.push(api("GET", `/api/v1/process-interactions?processId=${encodeURIComponent(p.processId)}&window=1ns`)
        .then((g) => portsCache.set(p.processId, g.ports || []))
        .catch(() => portsCache.set(p.processId, [])));
    }
    await Promise.all(tasks);
  };

  const toggle = async (id) => {
    const p = graph.participants.find((x) => x.id === id);
    if (!p || p.kind !== "process") return;
    if (expanded.has(id)) { expanded.delete(id); return draw(); }
    expanded.add(id);
    await loadModel(p);
    if (!isSuperseded()) await draw();
  };

  $("ix-canvas").addEventListener("click", (e) => {
    const open = e.target.closest(".ix-pool-open");
    if (open) {
      const p = graph.participants.find((x) => x.id === open.dataset.id);
      if (p) location.hash = `#/operations/interactions/${encodeURIComponent(p.processId)}`;
      return;
    }
    const tg = e.target.closest(".ix-pool-toggle");
    if (tg) toggle(tg.dataset.id);
  });
  $("ix-expand-all").addEventListener("click", async () => {
    const processes = graph.participants.filter((p) => p.kind === "process");
    for (const p of processes) expanded.add(p.id);
    await Promise.all(processes.map(loadModel));
    if (!isSuperseded()) await draw();
  });
  $("ix-collapse-all").addEventListener("click", () => { expanded.clear(); draw(); });

  const loadGraph = async () => {
    try {
      graph = await api("GET", query("/api/v1/process-interactions"));
    } catch (err) {
      if (isSuperseded()) return false;
      $("ix-canvas").innerHTML = `<p class="muted">${esc(err && err.status === 404 ? t("ix.unknown", { process: processId }) : t("ix.failed", { error: (err && err.message) || err }))}</p>`;
      return false;
    }
    if (isSuperseded()) return false;
    await draw();
    return true;
  };

  // ---------- the replay ----------

  let events = [];
  let index = 0;               // the next event to play
  let latest = "0";
  let playing = null, liveTimer = null;
  let reachedStart = true;
  let anim = 0;                // bumped to cancel envelopes still travelling

  const nowLabel = () => {
    const ev = events[Math.min(index, events.length) - 1];
    $("ix-now").textContent = events.length
      ? t("ix.replay.at", { at: ev ? fmtDateTime(ev.at) : "—", i: index, n: events.length })
      : t("ix.replay.empty");
    $("ix-scrub").max = String(events.length);
    $("ix-scrub").value = String(index);
  };

  const historyLabel = () => {
    if (!events.length) { $("ix-history").textContent = ""; return; }
    const from = fmtDateTime(events[0].at);
    $("ix-history").textContent = reachedStart
      ? t("ix.history.complete", { at: from, retention: fmtRetention(graph ? graph.retention : "") })
      : t("ix.history.cut", { at: from });
  };

  const feedLine = (ev) => {
    const name = (id) => {
      const p = graph && graph.participants.find((x) => x.id === id);
      return p ? label(p) : id;
    };
    const what = {
      received: t("ix.event.received"), started: t("ix.event.started"),
      unreceived: t("ix.event.unreceived"), outside: t("ix.event.outside", { n: ev.count }),
    }[ev.kind] || ev.kind;
    const route = ev.to ? `${name(ev.from)} → ${name(ev.to)}` : name(ev.from);
    const li = document.createElement("li");
    li.className = `ix-ev kind-${ev.kind}`;
    li.dataset.kind = ev.kind;
    li.innerHTML = `<span class="muted">${esc(fmtDateTime(ev.at))}</span> <code>${esc(ev.message)}</code> ${esc(route)} · ${esc(what)}${ev.correlationKey ? ` <span class="chip">${esc(ev.correlationKey)}</span>` : ""}`;
    return li;
  };

  const showFeed = (played) => {
    const feed = $("ix-feed");
    for (const ev of played) feed.prepend(feedLine(ev));
    while (feed.children.length > 8) feed.lastChild.remove();
  };

  // envelope moves a dot along the event's message flow; a send that reached nobody
  // leaves its sender's pool and stops just outside it.
  const envelope = (ev) => {
    if (!surface || !drawn) return;
    const viewer = surface.viewer;
    const canvas = viewer.get("canvas"), registry = viewer.get("elementRegistry");
    const layer = canvas.getLayer("ix-replay", 900);
    let wps;
    const flowId = ev.to ? drawn.flows.get(edgeKey(ev.from, ev.to, ev.message)) : null;
    const conn = flowId && registry.get(flowId);
    if (conn && conn.waypoints && conn.waypoints.length > 1) {
      wps = conn.waypoints.map((w) => ({ x: w.x, y: w.y }));
      canvas.addMarker(flowId, "ix-active");
    } else {
      const pool = drawn.pools.get(ev.from);
      if (!pool) return;
      const x = pool.x + pool.width - 60;
      wps = [{ x, y: pool.y + pool.height }, { x, y: pool.y + pool.height + 40 }];
    }
    const token = anim;
    surface.dot(layer, wps, TICK_MS * 0.85, () => token !== anim || isSuperseded())
      .finally(() => { if (conn) { try { canvas.removeMarker(flowId, "ix-active"); } catch { /* redrawn */ } } });
  };

  // pulse marks each message flow with how many of a step's events it carried.
  const pulse = (counts) => {
    if (!surface) return;
    const viewer = surface.viewer;
    const canvas = viewer.get("canvas"), overlays = viewer.get("overlays");
    for (const [flowId, n] of counts) {
      try {
        canvas.addMarker(flowId, "ix-pulse");
        const oid = overlays.add(flowId, "ix-count", { position: { top: -18, left: 4 }, html: `<span class="ix-pulse-count">+${n}</span>` });
        setTimeout(() => {
          try { canvas.removeMarker(flowId, "ix-pulse"); overlays.remove(oid); } catch { /* redrawn */ }
        }, TICK_MS * 0.85);
      } catch { /* the flow is not drawn */ }
    }
  };

  const speed = () => Number($("ix-speed").value) || 1;

  const step = () => {
    if (index >= events.length) { pause(); return; }
    const n = speed();
    const played = events.slice(index, index + n);
    index += played.length;
    if (n === 1) {
      $("ix-mode").textContent = t("ix.mode.single");
      played.forEach(envelope);
    } else {
      $("ix-mode").textContent = t("ix.mode.dense");
      const counts = new Map();
      for (const ev of played) {
        const id = ev.to && drawn ? drawn.flows.get(edgeKey(ev.from, ev.to, ev.message)) : null;
        if (id) counts.set(id, (counts.get(id) || 0) + ev.count);
      }
      pulse(counts);
    }
    showFeed(played);
    nowLabel();
  };

  const pause = () => {
    if (playing) { clearInterval(playing); playing = null; }
    $("ix-play").textContent = t("ix.replay.play");
  };
  const play = () => {
    if (index >= events.length) index = 0;
    pause();
    $("ix-play").textContent = t("ix.replay.pause");
    step();
    playing = setInterval(() => { if (isSuperseded()) { stopAll(); return; } step(); }, TICK_MS);
  };

  // loadHistory reads the replay backwards until the history begins or the page holds
  // as many events as it keeps.
  const loadHistory = async () => {
    events = []; index = 0; latest = "0"; reachedStart = true;
    $("ix-feed").innerHTML = "";
    let before = "";
    for (;;) {
      let page;
      try {
        page = await api("GET", query("/api/v1/process-interactions/replay", { limit: String(PAGE), ...(before ? { before } : {}) }));
      } catch { break; }
      if (isSuperseded() || !page) return;
      if (latest === "0") latest = page.latest || "0";
      events = (page.events || []).concat(events);
      if (!page.more) break;
      if (events.length >= MAX_EVENTS) { reachedStart = false; break; }
      before = page.next;
    }
    if (events.length > MAX_EVENTS) { events = events.slice(events.length - MAX_EVENTS); reachedStart = false; }
    historyLabel();
    nowLabel();
  };

  // follow reads what came after the newest event and appends it; an exchange the
  // drawing does not have yet redraws the collaboration first.
  const follow = async () => {
    if (isSuperseded()) { stopAll(); return; }
    let page;
    try { page = await api("GET", query("/api/v1/process-interactions/replay", { after: latest, limit: String(PAGE) })); } catch { return; }
    if (isSuperseded() || !page) return;
    latest = page.latest || latest;
    const fresh = page.events || [];
    if (!fresh.length) return;
    const unknown = fresh.some((ev) => ev.to && !(drawn && drawn.flows.has(edgeKey(ev.from, ev.to, ev.message))));
    if (unknown) await loadGraph();
    const wasAtEnd = index >= events.length;
    events = events.concat(fresh);
    if (events.length > MAX_EVENTS) {
      const drop = events.length - MAX_EVENTS;
      events = events.slice(drop); index = Math.max(0, index - drop); reachedStart = false;
    }
    historyLabel();
    if (wasAtEnd && !playing) { const n = fresh.length; for (let i = 0; i < n; i++) step(); }
    nowLabel();
  };

  const stopAll = () => {
    pause();
    anim++;
    if (liveTimer) { clearInterval(liveTimer); liveTimer = null; }
  };
  window.__atlasCleanup = () => {
    stopAll();
    if (surface) surface.destroy();
  };

  $("ix-play").addEventListener("click", () => (playing ? pause() : play()));
  $("ix-step").addEventListener("click", () => { pause(); step(); });
  $("ix-rewind").addEventListener("click", () => { pause(); anim++; index = 0; $("ix-feed").innerHTML = ""; nowLabel(); });
  $("ix-scrub").addEventListener("input", (e) => { pause(); index = Number(e.target.value) || 0; nowLabel(); });
  $("ix-live").addEventListener("change", (e) => {
    if (liveTimer) { clearInterval(liveTimer); liveTimer = null; }
    if (e.target.checked) { index = events.length; nowLabel(); liveTimer = setInterval(follow, LIVE_MS); }
  });
  $("ix-window").addEventListener("change", async (e) => {
    windowArg = e.target.value;
    const q = new URLSearchParams({ window: windowArg });
    history.replaceState(null, "", `#/operations/interactions/${encodeURIComponent(processId)}?${q}`);
    stopAll();
    $("ix-live").checked = false;
    if (await loadGraph()) await loadHistory();
  });

  if (await loadGraph()) await loadHistory();
}
