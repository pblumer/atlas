package archsketch

import (
	"bytes"
	"strings"
	"testing"
)

func blueprintMeta() Meta {
	return Meta{Application: "Rechnungswesen", Blueprint: &BlueprintOrigin{
		ID: "org.example.rechnung", Version: "1.2.0", Digest: "sha256:" + strings.Repeat("a", 64),
	}}
}

// TestABlueprintSketchSaysItIsAPreviewOfAPackage: a sketch derived from an atlas hub
// package before any installation read it is not the sketch of a release, and a reader
// who takes it for one is told something false — a release number nobody minted, a
// moment nobody took it at. It names the package, its version and digest instead, and
// says that the release a later publish records can differ.
func TestABlueprintSketchSaysItIsAPreviewOfAPackage(t *testing.T) {
	s := sample()
	s.TakenAt = 0
	s.Normalize()
	out := SVG(s, blueprintMeta())
	assertWellFormed(t, out)
	text := string(out)
	for _, want := range []string{
		"Architecture sketch — Rechnungswesen 1.2.0 (atlas hub)",
		"Blueprint 1.2.0",
		"Preview of atlas hub package org.example.rechnung 1.2.0",
		"sha256:" + strings.Repeat("a", 64),
		"before any installation read it",
		"a release published after installing records its own sketch",
		"nothing here was drawn by a person",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("blueprint SVG lacks %q", want)
		}
	}
	for _, banned := range []string{"Release v0", "release v0", "snapshot taken", "at an unrecorded time"} {
		if strings.Contains(text, banned) {
			t.Errorf("blueprint SVG says %q, which describes a release, not a package", banned)
		}
	}
	if !bytes.Equal(out, SVG(s, blueprintMeta())) {
		t.Error("the same package drew different bytes")
	}
}

// TestAReleaseSketchIsUnchangedByTheBlueprintOrigin: the origin is opt-in, so every
// release keeps the bytes it drew before.
func TestAReleaseSketchIsUnchangedByTheBlueprintOrigin(t *testing.T) {
	s := sample()
	s.Normalize()
	text := string(SVG(s, meta()))
	if strings.Contains(text, "atlas hub") || !strings.Contains(text, "Generated by Atlas from release v7 of Rechnungswesen") {
		t.Error("a release sketch changed its stamp")
	}
}

// TestAPackagedSnapshotClaimsNothingAboutAnInstallation: a preview has read no
// installation, so a name with nobody recorded at its other end, or a call into a
// process outside the package, must not read as "there is none here".
func TestAPackagedSnapshotClaimsNothingAboutAnInstallation(t *testing.T) {
	s := sample()
	s.TakenAt = 0
	s.Packaged = true
	s.Dependencies[1].TargetApplicationID, s.Dependencies[1].TargetApplication = "", ""
	s.Coupling = &Coupling{Names: []NameUse{
		{Kind: NameMessage, Name: "rechnung-gestellt", Direction: DirectionOut, UsedBy: []Use{{ProcessID: "rechnung", ElementID: "Throw"}}},
		{Kind: NameSignal, Name: "storno", Direction: DirectionIn, UsedBy: []Use{{ProcessID: "rechnung", ElementID: "Catch"}}},
	}}
	s.Data = &Data{}
	s.Processes = append(s.Processes, Process{ProcessID: "kaputt", Unread: true})
	s.Normalize()
	text := string(SVG(s.Select(SelectionOf(LayerApplication, LayerData)), blueprintMeta()))
	for _, banned := range []string{"no other application here", "not deployed here when recorded", "This release", "when the snapshot was taken"} {
		if strings.Contains(text, banned) {
			t.Errorf("packaged SVG says %q about an installation it never read", banned)
		}
	}
	for _, want := range []string{"whatever the installation runs", "not in this package", "capability register holds them",
		"This package declares no data objects", "could not be read from the package", "sha256:aaaaaaaaaaaa…"} {
		if !strings.Contains(text, want) {
			t.Errorf("packaged SVG lacks %q", want)
		}
	}
}
